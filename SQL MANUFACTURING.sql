SELECT DC.IDCustomer,DC.Customer_Name AS CUSTOMER,YEAR(F.DATE) AS [YEAR],AVG(F.TotalPrice)AS AVERAGE_PRICE
FROM DIM_CUSTOMER AS DC
INNER JOIN FACT_TRANSACTIONS AS F
ON DC.IDCustomer = F.IDCustomer
WHERE YEAR(F.DATE) ='2009'
GROUP BY DC.IDCustomer ,DC.Customer_Name,YEAR(F.DATE)
HAVING AVG(F.TOTALPRICE)>'500'
ORDER BY AVERAGE_PRICE DESC
