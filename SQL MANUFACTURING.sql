SELECT DM.Manufacturer_Name AS MANUFACTURER, D.IDModel,D.Model_Name AS MODEL,AVG(TOTALPRICE) AS AVERAGEPRICE,
 SUM(QUANTITY) AS TOTAL_QUANTITY
 FROM FACT_TRANSACTIONS AS F
 INNER JOIN DIM_MODEL AS D
 ON D.IDModel =F.IDModel
 INNER JOIN DIM_MANUFACTURER AS DM
 ON D.IDManufacturer = DM.IDManufacturer
 WHERE DM.Manufacturer_Name IN (SELECT TOP 5 DM.Manufacturer_Name AS MANUFACTURER
                  FROM DIM_MANUFACTURER AS DM
                  INNER JOIN DIM_MODEL AS D
                  ON DM.IDManufacturer =D.IDManufacturer
                  INNER JOIN FACT_TRANSACTIONS AS F
                  ON D.IDModel =F.IDModel
				  GROUP BY DM.IDManufacturer,DM.Manufacturer_Name
				  ORDER BY SUM(Quantity) DESC)
GROUP BY DM.Manufacturer_Name,D.IDModel,D.Model_Name 
ORDER BY AVERAGEPRICE DESC
 
 --Q5--END

