SELECT DISTINCT DL.State AS [STATE]
FROM FACT_TRANSACTIONS AS F
INNER JOIN DIM_LOCATION AS DL
ON F.IDLocation=DL.IDLocation
WHERE YEAR(F.DATE)>='2005'
GROUP BY DL.State
--Q1--END

--Q2--BEGIN
SELECT DM.Manufacturer_Name AS MANUFACTURER,State,Country,COUNT(DL.STATE) AS COUNT_PER_STATE
FROM DIM_LOCATION AS DL
INNER JOIN FACT_TRANSACTIONS AS F
ON DL.IDLocation = F.IDLocation
INNER JOIN DIM_MODEL AS DD
ON F.IDModel = DD.IDModel
INNER JOIN DIM_MANUFACTURER AS DM
ON DD.IDManufacturer = DM.IDManufacturer
WHERE Country ='US'
       AND
 DM.Manufacturer_Name='SAMSUNG'
 GROUP BY DM.Manufacturer_Name,State,Country
 ORDER BY COUNT_PER_STATE

 
--Q2--END

